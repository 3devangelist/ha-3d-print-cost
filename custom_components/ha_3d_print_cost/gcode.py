"""Read the slicer estimates of a G-code file that has not been printed yet.

Only the metadata written by the slicer is read (header / footer comments and,
for ``.gcode.3mf``, ``Metadata/slice_info.config``). Moves are never parsed:
the real consumption of printed jobs stays HaspelSync's job.

Supported:

* ``.gcode.3mf`` from Bambu Studio / Orca Slicer (``slice_info.config``,
  falling back to the header of ``Metadata/plate_N.gcode``);
* plain ``.gcode`` from Bambu Studio, Orca Slicer, PrusaSlicer and forks.

No Home Assistant import: fully unit-testable. Functions here do blocking
file IO and must run in the executor.
"""

from __future__ import annotations

import re
import zipfile
from dataclasses import dataclass, field
from pathlib import Path
from xml.etree import ElementTree as ET

# Slicers write their summary in the first lines (Bambu) or at the end of the
# file (Prusa / Orca config block). Reading both ends is enough, even for
# multi-hundred-MB files.
_HEAD_BYTES = 512 * 1024
_TAIL_BYTES = 512 * 1024

_PLATE_GCODE = re.compile(r"^Metadata/plate_(\d+)\.gcode$")


class GcodeError(ValueError):
    """The file cannot be read or holds no usable slicer estimate."""


@dataclass(slots=True)
class SlicedFilament:
    """One filament (slicer extruder / colour index) of a sliced plate."""

    index: int  # 1-based, as in the slicer
    weight_g: float
    material: str | None = None
    color: str | None = None  # "#RRGGBB"
    length_m: float | None = None


@dataclass(slots=True)
class GcodeInfo:
    """Slicer estimates of one plate."""

    duration_s: float | None
    filaments: list[SlicedFilament]
    slicer: str | None = None
    plate: int | None = None
    plates: list[int] = field(default_factory=list)

    @property
    def weight_g(self) -> float | None:
        """Total sliced weight."""
        if not self.filaments:
            return None
        return sum(f.weight_g for f in self.filaments)


# --------------------------------------------------------------------------- #
# Small parsers
# --------------------------------------------------------------------------- #
_DURATION_PART = re.compile(r"(\d+(?:\.\d+)?)\s*([dhms])", re.IGNORECASE)
_SECONDS = {"d": 86400, "h": 3600, "m": 60, "s": 1}


def parse_duration(text: str) -> float | None:
    """'1d 2h 3m 4s' / '2h 5m' / '45s' -> seconds."""
    parts = _DURATION_PART.findall(text)
    if not parts:
        return None
    return sum(float(value) * _SECONDS[unit.lower()] for value, unit in parts)


def _floats(text: str) -> list[float]:
    values: list[float] = []
    for item in re.split(r"[,;]", text):
        try:
            values.append(float(item.strip()))
        except ValueError:
            continue
    return values


def _strings(text: str) -> list[str]:
    return [item.strip().strip('"') for item in re.split(r"[;,]", text)]


def _hex(color: str | None) -> str | None:
    if not color:
        return None
    value = color.strip().lstrip("#")
    if not re.fullmatch(r"[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?", value):
        return None
    return f"#{value[:6].upper()}"


# --------------------------------------------------------------------------- #
# Plain G-code
# --------------------------------------------------------------------------- #
# "; key = value" (Prusa / Orca config) or "; key: value" (Bambu header).
_COMMENT = re.compile(r"^;\s*([^=:]+?)\s*[=:]\s*(.*?)\s*$")
_COMMENT_SEPARATOR = re.compile(r";\s+")
_SLICER_HINTS = ("slicer", "bambustudio", "generated by")


def _comments(text: str) -> dict[str, str]:
    """Every '; key = value' comment, first occurrence wins."""
    found: dict[str, str] = {}
    for line in text.splitlines():
        if not line.startswith(";"):
            continue
        # Bambu: "; model printing time: 1h 2m; total estimated time: 1h 10m".
        # List values ("PLA;PETG") have no space after the ';' and stay whole.
        for chunk in _COMMENT_SEPARATOR.split(line[1:]):
            if m := _COMMENT.match(f";{chunk}"):
                found.setdefault(m.group(1).strip().lower(), m.group(2))
    return found


def _first(comments: dict[str, str], *keys: str) -> str | None:
    for key in keys:
        if (value := comments.get(key)) not in (None, ""):
            return value
    return None


def parse_gcode_text(text: str) -> GcodeInfo:
    """Parse the comments of a plain G-code file (head + tail is enough)."""
    comments = _comments(text)

    weights_raw = _first(
        comments,
        "total filament weight [g]",  # Bambu Studio / Orca header
        "filament used [g]",  # PrusaSlicer / Orca footer
        "total filament used [g]",
    )
    weights = _floats(weights_raw) if weights_raw else []
    if not weights:
        raise GcodeError("no filament weight found in the G-code comments")

    lengths_raw = _first(comments, "total filament length [mm]", "filament used [mm]")
    lengths_mm = _floats(lengths_raw) if lengths_raw else []
    materials = _strings(comments.get("filament_type", ""))
    colors = _strings(comments.get("filament_colour", "") or comments.get("filament_color", ""))

    filaments = [
        SlicedFilament(
            index=i + 1,
            weight_g=weight,
            material=(materials[i] or None) if i < len(materials) else None,
            color=_hex(colors[i]) if i < len(colors) else None,
            length_m=lengths_mm[i] / 1000 if i < len(lengths_mm) else None,
        )
        for i, weight in enumerate(weights)
        if weight > 0
    ]

    duration_raw = _first(
        comments,
        "total estimated time",  # Bambu Studio header
        "estimated printing time (normal mode)",  # Prusa / Orca footer
        "estimated printing time",
        "model printing time",
    )
    slicer = next(
        (
            line.lstrip("; ").strip()
            for line in text.splitlines()[:5]
            if line.startswith(";") and any(hint in line.lower() for hint in _SLICER_HINTS)
        ),
        None,
    )
    return GcodeInfo(
        duration_s=parse_duration(duration_raw) if duration_raw else None,
        filaments=filaments,
        slicer=slicer,
    )


def _head_and_tail(raw: bytes) -> str:
    if len(raw) <= _HEAD_BYTES + _TAIL_BYTES:
        return raw.decode("utf-8", errors="replace")
    return (raw[:_HEAD_BYTES] + b"\n" + raw[-_TAIL_BYTES:]).decode("utf-8", errors="replace")


def _read_head_and_tail(path: Path) -> str:
    size = path.stat().st_size
    with path.open("rb") as handle:
        if size <= _HEAD_BYTES + _TAIL_BYTES:
            return handle.read().decode("utf-8", errors="replace")
        head = handle.read(_HEAD_BYTES)
        handle.seek(-_TAIL_BYTES, 2)
        tail = handle.read()
    return (head + b"\n" + tail).decode("utf-8", errors="replace")


# --------------------------------------------------------------------------- #
# Bambu .gcode.3mf
# --------------------------------------------------------------------------- #
def parse_slice_info(xml_text: str) -> dict[int, GcodeInfo]:
    """Parse ``Metadata/slice_info.config`` -> plate index -> estimates."""
    try:
        # ElementTree never resolves external entities; the file is local.
        root = ET.fromstring(xml_text)
    except ET.ParseError as err:
        raise GcodeError(f"slice_info.config is not valid XML: {err}") from err

    slicer = None
    if (header := root.find("header")) is not None:
        items = {i.get("key"): i.get("value") for i in header.findall("header_item")}
        app, version = items.get("X-BBL-Client-Type"), items.get("X-BBL-Client-Version")
        slicer = " ".join(p for p in (app, version) if p) or None

    plates: dict[int, GcodeInfo] = {}
    for plate in root.findall("plate"):
        meta = {m.get("key"): m.get("value") for m in plate.findall("metadata")}
        try:
            index = int(meta.get("index") or 0)
        except ValueError:
            continue
        filaments = []
        for item in plate.findall("filament"):
            try:
                weight = float(item.get("used_g") or 0)
            except ValueError:
                continue
            if weight <= 0:
                continue
            try:
                length_m = float(item.get("used_m")) if item.get("used_m") else None
            except ValueError:
                length_m = None
            filaments.append(
                SlicedFilament(
                    index=int(item.get("id") or len(filaments) + 1),
                    weight_g=weight,
                    material=item.get("type") or None,
                    color=_hex(item.get("color")),
                    length_m=length_m,
                )
            )
        try:
            duration = float(meta["prediction"]) if meta.get("prediction") else None
        except ValueError:
            duration = None
        plates[index] = GcodeInfo(duration_s=duration, filaments=filaments, slicer=slicer, plate=index)
    return plates


def _parse_3mf(path: Path, plate: int | None) -> GcodeInfo:
    try:
        archive = zipfile.ZipFile(path)
    except zipfile.BadZipFile as err:
        raise GcodeError("not a valid .3mf archive") from err

    with archive:
        names = archive.namelist()
        gcode_plates = sorted(int(m.group(1)) for n in names if (m := _PLATE_GCODE.match(n)))

        sliced: dict[int, GcodeInfo] = {}
        if "Metadata/slice_info.config" in names:
            sliced = parse_slice_info(archive.read("Metadata/slice_info.config").decode("utf-8", errors="replace"))
            # Only plates that were actually sliced carry a G-code.
            if gcode_plates:
                sliced = {i: info for i, info in sliced.items() if i in gcode_plates}
        available = sorted(set(sliced) | set(gcode_plates))
        if not available:
            raise GcodeError("the .3mf contains no sliced plate (export it with 'Export plate sliced file')")

        if plate is None:
            if len(available) > 1:
                raise GcodeError(f"the file has several sliced plates {available}: choose one with 'plate'")
            plate = available[0]
        if plate not in available:
            raise GcodeError(f"plate {plate} is not sliced in this file (available: {available})")

        info = sliced.get(plate)
        if info is None or not info.filaments:
            info = parse_gcode_text(_head_and_tail(archive.read(f"Metadata/plate_{plate}.gcode")))
        info.plate = plate
        info.plates = available
        return info


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #
def read_gcode_file(path: str | Path, plate: int | None = None) -> GcodeInfo:
    """Read the slicer estimates of ``.gcode`` or ``.gcode.3mf`` (blocking IO)."""
    path = Path(path)
    if not path.is_file():
        raise GcodeError(f"file not found: {path}")
    if path.suffix.lower() == ".3mf":
        return _parse_3mf(path, plate)
    try:
        text = _read_head_and_tail(path)
    except OSError as err:
        raise GcodeError(f"cannot read {path.name}: {err}") from err
    return parse_gcode_text(text)
