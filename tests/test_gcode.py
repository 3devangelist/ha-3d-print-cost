"""Slicer metadata parsing (no G-code move is ever parsed)."""

import zipfile
from pathlib import Path

import pytest

from custom_components.ha_3d_print_cost.gcode import (
    GcodeError,
    parse_duration,
    parse_gcode_text,
    parse_slice_info,
    read_gcode_file,
)

BAMBU_GCODE = """; HEADER_BLOCK_START
; BambuStudio 02.02.00.85
; model printing time: 1h 2m 3s; total estimated time: 1h 10m 5s
; total layer number: 150
; total filament length [mm] : 20123.45,7432.10
; total filament volume [cm^3] : 48400.00,17800.00
; total filament weight [g] : 62.40,22.20
; filament_density: 1.24,1.24
; HEADER_BLOCK_END

; CONFIG_BLOCK_START
; filament_type = PLA;PLA
; filament_colour = #000000;#ffffff
; CONFIG_BLOCK_END
G28
G1 X10 Y10
"""

PRUSA_GCODE = """; generated by PrusaSlicer 2.8.1 on 2026-10-20 at 10:00:00 UTC
G28
G1 X10
; filament used [mm] = 1500.00, 0.00, 300.00
; filament used [g] = 4.47, 0.00, 0.89
; total filament used [g] = 5.36
; estimated printing time (normal mode) = 1d 2h 3m 4s
; filament_type = PETG;PLA;TPU
; filament_colour = #FF0000;#00FF00;#0000FF
"""

SLICE_INFO = """<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="X-BBL-Client-Type" value="slicer"/>
    <header_item key="X-BBL-Client-Version" value="02.02.00.85"/>
  </header>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="12642"/>
    <metadata key="weight" value="84.60"/>
    <filament id="1" type="PLA" color="#000000" used_m="20.12" used_g="62.40"/>
    <filament id="3" type="PLA" color="#FFFFFFFF" used_m="7.43" used_g="22.20"/>
  </plate>
  <plate>
    <metadata key="index" value="2"/>
    <metadata key="prediction" value="600"/>
    <filament id="2" type="PETG" color="#FF0000" used_m="1.0" used_g="3.00"/>
  </plate>
</config>
"""


def make_3mf(path: Path, *, plates: dict[int, str], slice_info: str | None = SLICE_INFO) -> Path:
    with zipfile.ZipFile(path, "w") as archive:
        if slice_info is not None:
            archive.writestr("Metadata/slice_info.config", slice_info)
        for index, gcode in plates.items():
            archive.writestr(f"Metadata/plate_{index}.gcode", gcode)
    return path


@pytest.mark.parametrize(
    ("text", "seconds"),
    [("1h 2m 3s", 3723), ("2m 5s", 125), ("45s", 45), ("1d 2h 3m 4s", 93784), ("nothing", None)],
)
def test_parse_duration(text, seconds) -> None:
    assert parse_duration(text) == seconds


def test_bambu_gcode_header() -> None:
    info = parse_gcode_text(BAMBU_GCODE)
    assert info.slicer == "BambuStudio 02.02.00.85"
    assert info.duration_s == 4205  # total estimated time, not model time
    assert [(f.index, f.weight_g, f.material, f.color) for f in info.filaments] == [
        (1, 62.4, "PLA", "#000000"),
        (2, 22.2, "PLA", "#FFFFFF"),
    ]
    assert info.weight_g == pytest.approx(84.6)
    assert info.filaments[0].length_m == pytest.approx(20.12345)


def test_prusa_footer_skips_unused_extruders() -> None:
    info = parse_gcode_text(PRUSA_GCODE)
    assert info.duration_s == 93784
    # Extruder 2 is unused (0 g) but extruder 3 keeps its own index/material.
    assert [(f.index, f.weight_g, f.material) for f in info.filaments] == [(1, 4.47, "PETG"), (3, 0.89, "TPU")]


def test_gcode_without_weight_is_rejected() -> None:
    with pytest.raises(GcodeError):
        parse_gcode_text("G28\nG1 X1\n")


def test_slice_info_plates() -> None:
    plates = parse_slice_info(SLICE_INFO)
    assert set(plates) == {1, 2}
    plate = plates[1]
    assert plate.duration_s == 12642
    assert plate.slicer == "slicer 02.02.00.85"
    assert [(f.index, f.weight_g, f.color) for f in plate.filaments] == [(1, 62.4, "#000000"), (3, 22.2, "#FFFFFF")]


def test_read_plain_gcode_file(tmp_path: Path) -> None:
    path = tmp_path / "lamp.gcode"
    path.write_text(BAMBU_GCODE)
    assert read_gcode_file(path).weight_g == pytest.approx(84.6)


def test_read_large_gcode_reads_head_and_tail(tmp_path: Path) -> None:
    path = tmp_path / "big.gcode"
    path.write_text(BAMBU_GCODE + "G1 X1 Y1 E0.1\n" * 200_000 + "; footer = 1\n")
    assert read_gcode_file(path).duration_s == 4205


def test_3mf_single_sliced_plate(tmp_path: Path) -> None:
    # Only plate 1 has a G-code: plate 2 in slice_info is ignored.
    path = make_3mf(tmp_path / "lamp.gcode.3mf", plates={1: BAMBU_GCODE})
    info = read_gcode_file(path)
    assert info.plate == 1
    assert info.plates == [1]
    assert info.duration_s == 12642  # from slice_info, preferred over the header
    assert info.weight_g == pytest.approx(84.6)


def test_3mf_several_plates_needs_a_choice(tmp_path: Path) -> None:
    path = make_3mf(tmp_path / "multi.gcode.3mf", plates={1: BAMBU_GCODE, 2: BAMBU_GCODE})
    with pytest.raises(GcodeError, match="several sliced plates"):
        read_gcode_file(path)
    info = read_gcode_file(path, plate=2)
    assert info.plate == 2
    assert [(f.material, f.weight_g) for f in info.filaments] == [("PETG", 3.0)]
    with pytest.raises(GcodeError, match="not sliced"):
        read_gcode_file(path, plate=5)


def test_3mf_without_slice_info_uses_plate_gcode(tmp_path: Path) -> None:
    path = make_3mf(tmp_path / "old.gcode.3mf", plates={1: BAMBU_GCODE}, slice_info=None)
    info = read_gcode_file(path)
    assert info.duration_s == 4205
    assert info.weight_g == pytest.approx(84.6)


def test_unsliced_3mf_and_bad_files(tmp_path: Path) -> None:
    project = make_3mf(tmp_path / "project.3mf", plates={}, slice_info=None)
    with pytest.raises(GcodeError, match="no sliced plate"):
        read_gcode_file(project)
    broken = tmp_path / "broken.3mf"
    broken.write_text("not a zip")
    with pytest.raises(GcodeError, match="not a valid"):
        read_gcode_file(broken)
    with pytest.raises(GcodeError, match="not found"):
        read_gcode_file(tmp_path / "missing.gcode")
